# Generates shared/RogueStars.Rules/Content/ContentDb.PartData.g.cs from data.py: every approved part text (Epic, Legendary,
# Mythic and awakened), the Mythic names and identities. Run from anywhere: python3 docs/design/parts-v2/gen_cs.py
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from data import *

OUT = os.path.normpath(os.path.join(HERE, '../../../shared/RogueStars.Rules/Content/ContentDb.PartData.g.cs'))


def cs(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


L_ = []
P = L_.append
P('// <auto-generated> docs/design/parts-v2/gen_cs.py from docs/design/parts-v2/data.py (the approved parts redesign). Do not edit by hand. </auto-generated>')
P('using System.Collections.Generic;')
P('')
P('namespace RogueStars.Rules.Content')
P('{')
P('    public sealed partial class ContentDb')
P('    {')
P('        /// <summary>Approved skill texts of the standard parts: key "Epic|Slot|Role|i" / "Legendary|Slot|Role|i".</summary>')
P('        internal static readonly Dictionary<string, string> PartStdTexts = new Dictionary<string, string>')
P('        {')
for (slot, role), sk in E.items():
    for i, (t, e) in enumerate(sk):
        P(f'            [{cs(f"Epic|{slot}|{role}|{i}")}] = {cs(t)},')
for (slot, role), sk in L.items():
    for i, (t, e) in enumerate(sk):
        P(f'            [{cs(f"Legendary|{slot}|{role}|{i}")}] = {cs(t)},')
P('        };')
P('')
P('        /// <summary>One approved Mythic (data.py): id, names, slot, synergy, identity, synergy stat, five skills and their awakened versions.</summary>')
P('        internal sealed class MythicData')
P('        {')
P('            public string Id, Name, AwakenedName, Slot, Synergy, Identity, Stat;')
P('            public string[] Skills, Awakened;')
P('        }')
P('')
P('        internal static readonly MythicData[] PartMythicData =')
P('        {')
for m in M:
    sk = ', '.join(cs(t) for t, e in m['skills'])
    aw = ', '.join(cs(t) for t, e in m['awk'])
    P(f'            new MythicData {{ Id = {cs(m["id"])}, Name = {cs(m["name"])}, AwakenedName = {cs(m["aw"])}, Slot = {cs(m["slot"])}, Synergy = {cs(m["syn"])}, Identity = {cs(m["identity"])}, Stat = {cs(m["stat"])},')
    P(f'                Skills = new[] {{ {sk} }},')
    P(f'                Awakened = new[] {{ {aw} }} }},')
P('        };')
P('    }')
P('}')
open(OUT, 'w').write('\n'.join(L_) + '\n')
print('wrote', OUT)
