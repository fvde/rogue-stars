using System.Text;

namespace RogueStars.Sim;

/// <summary>Markdown tables for docs/balance (generated part of the progression report) and the console summary.</summary>
public static class Report
{
    public static readonly int[] HeadlineDays = { 1, 7, 30, 90, 180, 365, 730 };

    /// <summary>Metrics shown in the per-checkpoint tables (name, label).</summary>
    public static readonly (string m, string label)[] KeyMetrics =
    {
        ("power", "Power"), ("main_level", "Main level"), ("overcharged_cleared", "OC cleared"), ("burrow_floors", "Burrow floors"),
        ("darkside_cleared", "Dark Side"), ("worm_level", "Worm lv"), ("talent_tier", "Talent tier"), ("part_rarity_avg", "Part rarity avg"),
        ("part_level_avg", "Part lv avg"), ("rune_slots", "Rune slots"), ("rune_rarity_avg", "Rune rarity"), ("forge_unlocks", "Forge"),
        ("parts_awakened", "Awakened parts"), ("hero_stars_best", "Hero ★ best"), ("hero_stars_avg", "Hero ★ avg"), ("heroes_owned", "Heroes"),
        ("mount_stars_best", "Mount ★"), ("mount_awaken_best", "Mount awaken"), ("blueprints_owned", "Blueprints"), ("blueprint_stars_avg", "BP ★ avg"),
        ("buildings", "Buildings"), ("building_level_avg", "Bld lv avg"), ("prod_h_biomass", "Biomass/h"), ("prod_h_ore", "Ore/h"),
        ("prod_h_diamonds", "Diamonds/h"), ("aliens_owned", "Aliens"), ("alien_stars_avg", "Alien ★ avg"), ("squad_size", "Squad"),
        ("breeds", "Breeds"), ("lab_research", "Lab"), ("arena_league", "League"), ("invasion_score", "Invasion score"),
        ("gacha_mythics", "Mythic pulls"), ("bal_diamonds", "Diamonds"), ("bal_biomass", "Biomass"), ("bal_ore", "Ore"),
        ("bal_grain", "Grain"), ("bal_gear_cores", "Gear cores"), ("bal_fuel", "Fuel"), ("bal_hero_xp", "Hero XP"),
        ("bal_part_tokens", "Part tokens"), ("spent_usd", "Spent $"), ("minutes_per_day", "Min/day"),
    };

    public static string Summary(Dictionary<string, SortedDictionary<int, Dictionary<string, double>>> med, Analysis.Result a)
    {
        var sb = new StringBuilder();
        sb.AppendLine(HeadlineTable(med, "main_level", "Main level reached"));
        sb.AppendLine(HeadlineTable(med, "power", "Power"));
        sb.AppendLine(HeadlineTable(med, "hero_stars_best", "Best hero stars"));
        foreach (var p in a.Profiles)
        {
            sb.AppendLine("## " + p.Profile);
            foreach (var f in p.Flags) sb.AppendLine("- " + f);
        }
        return sb.ToString();
    }

    public static string HeadlineTable(Dictionary<string, SortedDictionary<int, Dictionary<string, double>>> med, string metric, string title)
    {
        var sb = new StringBuilder();
        var days = HeadlineDays.Where(d => med.Values.First().ContainsKey(d)).ToList();
        sb.AppendLine("**" + title + "** (median)");
        sb.AppendLine();
        sb.Append("| Profile |"); foreach (var d in days) sb.Append(" d").Append(d).Append(" |"); sb.AppendLine();
        sb.Append("|---|"); foreach (var _ in days) sb.Append("---|"); sb.AppendLine();
        foreach (var (profile, byDay) in med)
        {
            sb.Append("| ").Append(profile).Append(" |");
            foreach (var d in days) sb.Append(' ').Append(Output.F(byDay[d].GetValueOrDefault(metric, double.NaN))).Append(" |");
            sb.AppendLine();
        }
        return sb.ToString();
    }

    public static string CheckpointTable(Dictionary<string, SortedDictionary<int, Dictionary<string, double>>> med, int day)
    {
        var sb = new StringBuilder();
        var profiles = med.Keys.ToList();
        sb.Append("| Metric |"); foreach (var p in profiles) sb.Append(' ').Append(p).Append(" |"); sb.AppendLine();
        sb.Append("|---|"); foreach (var _ in profiles) sb.Append("---|"); sb.AppendLine();
        foreach (var (m, label) in KeyMetrics)
        {
            sb.Append("| ").Append(label).Append(" |");
            foreach (var p in profiles) sb.Append(' ').Append(Output.F(med[p].TryGetValue(day, out var x) ? x.GetValueOrDefault(m, double.NaN) : double.NaN)).Append(" |");
            sb.AppendLine();
        }
        return sb.ToString();
    }

    public static string AnalysisMarkdown(Analysis.Result a)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Simulation analysis (generated by tools/RogueStars.Sim)");
        sb.AppendLine();
        sb.AppendLine(HeadlineTable(a.Medians, "main_level", "Main level reached"));
        sb.AppendLine(HeadlineTable(a.Medians, "power", "Power"));
        sb.AppendLine(HeadlineTable(a.Medians, "worm_level", "Worm level"));
        sb.AppendLine(HeadlineTable(a.Medians, "hero_stars_best", "Best hero stars"));
        sb.AppendLine(HeadlineTable(a.Medians, "target_hero_stars", "Star Knight (whale target) stars"));
        sb.AppendLine(HeadlineTable(a.Medians, "mount_stars_best", "Best mount stars"));
        sb.AppendLine(HeadlineTable(a.Medians, "part_rarity_avg", "Avg equipped part rarity (0 Common … 4 Legendary … 5 Mythic … 8 Mythic S … 11 Mythic SS … 13 SS+2)"));
        sb.AppendLine(HeadlineTable(a.Medians, "building_level_avg", "Avg building level"));
        sb.AppendLine(HeadlineTable(a.Medians, "alien_stars_avg", "Avg alien stars"));
        sb.AppendLine(HeadlineTable(a.Medians, "gacha_mythics", "Mythic pulls (all types)"));
        sb.AppendLine(HeadlineTable(a.Medians, "spent_usd", "Money spent (USD)"));
        sb.AppendLine(HeadlineTable(a.Medians, "minutes_per_day", "Minutes played per day"));

        foreach (int day in new[] { 7, 30, 90, 365, 730 })
        {
            if (!a.Medians.Values.First().ContainsKey(day)) continue;
            sb.AppendLine("## Checkpoint day " + day);
            sb.AppendLine();
            sb.AppendLine(CheckpointTable(a.Medians, day));
        }

        sb.AppendLine("## Max days without a meaningful upgrade, per system (windows " + string.Join(", ", Analysis.Windows.Select(w => w.from + "–" + w.to)) + ")");
        sb.AppendLine();
        var systems = SystemEvents.Systems.Select(s => s.system).ToList();
        sb.Append("| Profile |"); foreach (var s in systems) sb.Append(' ').Append(s).Append(" |"); sb.AppendLine();
        sb.Append("|---|"); foreach (var _ in systems) sb.Append("---|"); sb.AppendLine();
        foreach (var p in a.Profiles)
        {
            sb.Append("| ").Append(p.Profile).Append(" |");
            foreach (var st in p.Systems) sb.Append(' ').Append(string.Join("/", st.MaxGap.Select(g => double.IsNaN(g) ? "–" : g.ToString("0")))).Append(" |");
            sb.AppendLine();
        }
        sb.AppendLine();
        sb.AppendLine("## Upgrades per 30 days, per system (same windows)");
        sb.AppendLine();
        sb.Append("| Profile |"); foreach (var s in systems) sb.Append(' ').Append(s).Append(" |"); sb.AppendLine();
        sb.Append("|---|"); foreach (var _ in systems) sb.Append("---|"); sb.AppendLine();
        foreach (var p in a.Profiles)
        {
            sb.Append("| ").Append(p.Profile).Append(" |");
            foreach (var st in p.Systems) sb.Append(' ').Append(string.Join("/", st.EventsPer30.Select(Output.F))).Append(" |");
            sb.AppendLine();
        }
        sb.AppendLine();
        sb.AppendLine("## Power growth per week (median, %) and share of flat 4-week windows");
        sb.AppendLine();
        sb.AppendLine("| Profile | " + string.Join(" | ", Analysis.Windows.Select(w => "d" + w.from + "–" + w.to)) + " |");
        sb.AppendLine("|---|" + string.Concat(Analysis.Windows.Select(_ => "---|")));
        foreach (var p in a.Profiles)
            sb.AppendLine("| " + p.Profile + " | " + string.Join(" | ", p.WeeklyGrowthPct.Select((g, i) => double.IsNaN(g) ? "–" : g.ToString("0.0") + "% (flat " + (p.FlatShare[i] * 100).ToString("0") + "%)")) + " |");
        sb.AppendLine();
        sb.AppendLine("## Currencies at the end: balance, days of income banked, share of income spent (last 90 days)");
        sb.AppendLine();
        var curs = SimPlayer.Tracked;
        sb.Append("| Profile |"); foreach (var c in curs) sb.Append(' ').Append(c).Append(" |"); sb.AppendLine();
        sb.Append("|---|"); foreach (var _ in curs) sb.Append("---|"); sb.AppendLine();
        foreach (var p in a.Profiles)
        {
            sb.Append("| ").Append(p.Profile).Append(" |");
            foreach (var c in p.Currencies)
                sb.Append(' ').Append(Output.F(c.Balance730)).Append(" / ").Append(c.DaysBanked730 >= 999 ? "∞" : c.DaysBanked730.ToString("0")).Append("d / ")
                  .Append(double.IsNaN(c.SpendShare730) ? "–" : (c.SpendShare730 * 100).ToString("0") + "%").Append(" |");
            sb.AppendLine();
        }
        sb.AppendLine();
        sb.AppendLine("## F2P → Whale ratios (median Whale / median F2P)");
        sb.AppendLine();
        var ratioMetrics = new[] { "power", "main_level", "worm_level", "part_rarity_avg", "hero_stars_best", "mount_stars_best", "building_level_avg", "alien_stars_avg", "gacha_mythics" };
        sb.AppendLine("| Time | Day | " + string.Join(" | ", ratioMetrics) + " |");
        sb.AppendLine("|---|---|" + string.Concat(ratioMetrics.Select(_ => "---|")));
        foreach (var t in TimeProfile.All)
        {
            string f2p = t.Name + " F2P", whale = t.Name + " Whale";
            if (!a.Medians.ContainsKey(f2p) || !a.Medians.ContainsKey(whale)) continue;
            foreach (int day in new[] { 7, 30, 90, 365, 730 })
            {
                if (!a.Medians[f2p].ContainsKey(day)) continue;
                sb.Append("| ").Append(t.Name).Append(" | ").Append(day).Append(" |");
                foreach (var m in ratioMetrics)
                {
                    double x = a.Medians[f2p][day][m], y = a.Medians[whale][day][m];
                    sb.Append(' ').Append(x > 0 ? (y / x).ToString("0.00") : "–").Append(" |");
                }
                sb.AppendLine();
            }
        }
        sb.AppendLine();
        sb.AppendLine("## Flags");
        foreach (var p in a.Profiles)
        {
            sb.AppendLine();
            sb.AppendLine("**" + p.Profile + "**");
            sb.AppendLine();
            if (p.Flags.Count == 0) sb.AppendLine("- none");
            foreach (var f in p.Flags) sb.AppendLine("- " + f);
        }
        return sb.ToString();
    }
}
