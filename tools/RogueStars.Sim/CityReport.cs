using RogueStars.Rules.Content;

namespace RogueStars.Sim;

/// <summary>
/// City redesign checks (City design §4 / §6): when the digs land, how the city fills, and how many pulls the pull buildings pay,
/// per profile (median over seeds). Written as docs/balance/data/city_&lt;label&gt;.md.
/// </summary>
public static class CityReport
{
    public static string Markdown(List<SimResult> results, ContentDb content, int days)
    {
        var sb = new System.Text.StringBuilder();
        sb.AppendLine("# City redesign: digs, buildings and pull buildings (generated by tools/RogueStars.Sim)");
        sb.AppendLine();
        var groups = results.GroupBy(r => r.Profile).ToList();
        var digDays = new[] { 5, 10, 15, 20 };
        sb.AppendLine("**Dig day** (median account day the n-th dig finished; design target for Active F2P in brackets)");
        sb.AppendLine();
        sb.AppendLine("| Profile | " + string.Join(" | ", digDays.Select(n => $"dig #{n} ({content.CityTuning.Digs[n - 1].TargetDay})")) + " |");
        sb.AppendLine("|---|" + string.Concat(digDays.Select(_ => "---|")));
        foreach (var g in groups)
            sb.AppendLine("| " + g.Key + " | " + string.Join(" | ", digDays.Select(n => F(Median(g.Select(r => (double)(r.Daily.FindIndex(d => d.Digs >= n) is int i && i >= 0 ? i + 1 : double.NaN)))))) + " |");
        sb.AppendLine();
        // Buildings come from their blueprint (owner, 2026-11-25): the day each building feature unlocked = the day its blueprint was
        // pulled (the Launch Pod comes with the Aliens unlock on the crash site), and the first finished research (the Laboratory
        // pulled, built, staffed).
        var gated = new[] { ("Launch Pod", RogueStars.Rules.Systems.Features.AlienSquad), ("Laboratory", RogueStars.Rules.Systems.Features.Laboratory),
            ("Ore Mine", RogueStars.Rules.Systems.Features.OreMine), ("Grain Farm", RogueStars.Rules.Systems.Features.GrainFarm),
            ("Breeding Pen", RogueStars.Rules.Systems.Features.Breeding) };
        sb.AppendLine("**Building blueprints** (median account day the blueprint arrived, i.e. its feature unlocked; – = not within the run; City = day the City opened)");
        sb.AppendLine();
        sb.AppendLine("| Profile | City | " + string.Join(" | ", gated.Select(x => x.Item1)) + " | first research |");
        sb.AppendLine("|---|---|" + string.Concat(gated.Select(_ => "---|")) + "---|");
        double UnlockDay(SimResult r, string id) => r.Unlocks.TryGetValue(id, out var u) ? u.day : double.NaN;
        string MedOrDash(IEnumerable<double> xs)
        {
            var l = xs.ToList();
            return l.Count(x => !double.IsNaN(x)) * 2 <= l.Count ? "–" : F(l.Select(x => double.IsNaN(x) ? double.MaxValue : x).OrderBy(x => x).ElementAt(l.Count / 2));
        }
        foreach (var g in groups)
            sb.AppendLine("| " + g.Key + " | " + MedOrDash(g.Select(r => UnlockDay(r, RogueStars.Rules.Systems.Features.BiomassFarm))) + " | "
                + string.Join(" | ", gated.Select(x => MedOrDash(g.Select(r => UnlockDay(r, x.Item2)))))
                + " | " + MedOrDash(g.Select(r => r.Daily.FindIndex(d => d.LabDone > content.LabResearch.Values.Count(x => x.DefaultResearched)) is int i && i >= 0 ? i + 1 : double.NaN)) + " |");
        sb.AppendLine();
        var cps = new[] { 7, 30, 90, 180, 365, 730 }.Where(d => d <= days).ToArray();
        void Table(string title, Func<DayRecord, double> f)
        {
            sb.AppendLine("**" + title + "** (median)");
            sb.AppendLine();
            sb.AppendLine("| Profile | " + string.Join(" | ", cps.Select(d => "d" + d)) + " |");
            sb.AppendLine("|---|" + string.Concat(cps.Select(_ => "---|")));
            foreach (var g in groups)
                sb.AppendLine("| " + g.Key + " | " + string.Join(" | ", cps.Select(d => F(Median(g.Where(r => r.Daily.Count >= d).Select(r => f(r.Daily[d - 1])))))) + " |");
            sb.AppendLine();
        }
        Table("Digs done", d => d.Digs);
        Table("Buildings placed / running", d => d.CityPlaced);
        Table("Buildings running (staffed)", d => d.CityRunning);
        Table("Pull buildings placed", d => d.PullBuildings);
        sb.AppendLine("**Pulls a day from pull buildings** (median over the 30 days before the checkpoint; per placed pull building in brackets)");
        sb.AppendLine();
        sb.AppendLine("| Profile | " + string.Join(" | ", cps.Where(d => d >= 30).Select(d => "d" + d)) + " |");
        sb.AppendLine("|---|" + string.Concat(cps.Where(d => d >= 30).Select(_ => "---|")));
        foreach (var g in groups)
            sb.AppendLine("| " + g.Key + " | " + string.Join(" | ", cps.Where(d => d >= 30).Select(d =>
            {
                double perDay = Median(g.Where(r => r.Daily.Count >= d).Select(r => (r.Daily[d - 1].CityPulls - r.Daily[d - 30].CityPulls) / 30.0));
                double per = Median(g.Where(r => r.Daily.Count >= d && r.Daily[d - 1].PullBuildings > 0)
                    .Select(r => (r.Daily[d - 1].CityPulls - r.Daily[d - 30].CityPulls) / 30.0 / r.Daily[d - 1].PullBuildings));
                return F(perDay) + " (" + F(per) + ")";
            })) + " |");
        sb.AppendLine();
        return sb.ToString();
    }

    private static double Median(IEnumerable<double> xs)
    {
        var l = xs.Where(x => !double.IsNaN(x)).OrderBy(x => x).ToList();
        return l.Count == 0 ? double.NaN : l[l.Count / 2];
    }

    private static string F(double v) => double.IsNaN(v) ? "–" : Math.Abs(v) >= 100 ? v.ToString("0") : v.ToString("0.##");
}
